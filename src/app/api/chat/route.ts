import { GoogleGenAI } from '@google/genai';

export async function POST(request: Request) {
  try {
    const { prompt, agent, history } = await request.json();
    const apiKey = process.env.GEMINI_API_KEY;

    if (!apiKey) {
      return Response.json({
        content: `QUBOT Autonomous execution mode active for ${agent.name}.`,
        reasoning: 'Autonomous engine operating without external API key.'
      });
    }

    const ai = new GoogleGenAI({ apiKey });
    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: `
You are ${agent.name}, an AI automation assistant inside QUBOT (${agent.role}).
System Instructions: ${agent.systemPrompt}
Available Tools: ${agent.enabledTools?.join(', ')}
User Request: ${prompt}
`
    });

    return Response.json({
      content: response.text || '',
      reasoning: `Generated by Gemini 3.8 Flash for QUBOT agent ${agent.name}`
    });
  } catch (error: any) {
    return Response.json({ error: error.message }, { status: 500 });
  }
}
